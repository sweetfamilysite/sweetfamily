    <h2>✅ O que você vai aprender nesta lição</h2>
    <ul>
      <li>Uso da partícula は para marcar o tema da frase</li>
      <li>Uso da partícula が para marcar o sujeito ou foco da frase</li>
      <li>Uso da partícula の para indicar posse e relação entre substantivos</li>
      <li>Exemplos práticos e exercícios para aplicar o conteúdo</li>
    </ul>

    <h3>📌 1) Partícula は (wa) — Tema da frase</h3>
    <p>Marca o tópico ou tema sobre o qual a frase fala.<br>
    Geralmente traduzido como “quanto a…” ou simplesmente indicado pelo contexto.</p>
    <p><strong>Exemplo:</strong><br>
    わたし は がくせい です。<br>
    (Eu sou estudante — “Quanto a mim, sou estudante.”)</p>

    <h3>📌 2) Partícula が (ga) — Sujeito / foco</h3>
    <p>Marca o sujeito da frase ou destaca algo novo ou importante.<br>
    Usado quando introduzimos um novo sujeito ou para enfatizar.</p>
    <p><strong>Exemplo:</strong><br>
    だれ が きましたか。<br>
    (Quem chegou?)<br>
    たなかさん が きました。<br>
    (O Sr. Tanaka chegou.)</p>

    <h3>📌 3) Partícula の (no) — Posse / relação</h3>
    <p>Indica posse ou relação entre dois substantivos, similar a “de” em português.</p>
    <p><strong>Exemplo:</strong><br>
    わたし の ほん。<br>
    (Meu livro.)<br>
    にほん の くるま。<br>
    (Carro do Japão / carro japonês.)</p>

    <h3>📌 4) Exemplos de Frases</h3>
