    <h3>📌 1) Partícula か — Indicar Pergunta</h3>
    <p>Colocamos か no final da frase para indicar que é uma pergunta.</p>
    <p><strong>Exemplo:</strong><br>これは ペン です。 (Isto é uma caneta.)<br>これは ペン です か。 (Isto é uma caneta?)</p>

