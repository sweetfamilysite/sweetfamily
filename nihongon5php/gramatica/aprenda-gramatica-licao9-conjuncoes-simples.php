    <h3>📌 1) Conjunção そして — E / Então</h3>
    <p>Usada para adicionar informações ou sequenciar ações.</p>
    <p><strong>Exemplo:</strong><br>わたし は ごはん を たべます。 そして、テレビ を みます。<br>(Eu como. E depois assisto TV.)</p>

    <h3>📌 2) Conjunção でも — Mas / Porém</h3>
    <p>Usada para mostrar contraste ou oposição entre ideias.</p>
    <p><strong>Exemplo:</strong><br>あめ が ふっています。 でも、さんぽ に いきます。<br>(Está chovendo. Mas vou passear.)</p>

    <h3>📌 3) Conjunção それから — Depois / Em seguida</h3>
    <p>Usada para indicar o próximo passo ou ação depois de outra.</p>
    <p><strong>Exemplo:</strong><br>かいしゃ に いきます。 それから、スーパー に いきます。<br>(Vou para o trabalho. Depois, vou ao supermercado.)</p>

    <h3>📌 4) Exemplos de Frases</h3>
