    <h3>📌 2) Adjetivos Na (な) — Exemplo e Conjugação</h3>
    <p>Adjetivos que não terminam em い e precisam da partícula な antes do substantivo.</p>
    <p>Exemplo: きれい (limpo, bonito), しずか (quieto)</p>
