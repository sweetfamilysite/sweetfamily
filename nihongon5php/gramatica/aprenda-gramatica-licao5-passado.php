    <h3>📌 1) Passado Afirmativo: Verbos com ました</h3>
    <p>Para formar o passado afirmativo, substituímos ます por ました na forma polida.</p>
    <p><strong>Exemplo:</strong><br>たべます → たべました (comi)<br>のみます → のみました (bebi)<br>いきます → いきました (fui)</p>

    <h3>📌 2) Passado Negativo: Verbos com ませんでした</h3>
    <p>Para formar o passado negativo, substituímos ます por ませんでした.</p>
    <p><strong>Exemplo:</strong><br>たべます → たべませんでした (não comi)<br>のみます → のみませんでした (não bebi)<br>いきます → いきませんでした (não fui)</p>

