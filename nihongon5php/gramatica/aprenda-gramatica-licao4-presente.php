    <h3>📌 1) Forma Afirmativa: Verbos com ます</h3>
    <p>Para conjugar verbos no presente afirmativo, adicionamos ます à raiz do verbo.</p>
    <p><strong>Exemplo:</strong><br>たべます (comer)<br>のみます (beber)<br>いきます (ir)</p>

    <h3>📌 2) Forma Negativa: Verbos com ません</h3>
    <p>Para negar verbos no presente, substituímos ます por ません.</p>
    <p><strong>Exemplo:</strong><br>たべません (não comer)<br>のみません (não beber)<br>いきません (não ir)</p>

    <h3>📌 3) Exemplos de Frases</h3>
