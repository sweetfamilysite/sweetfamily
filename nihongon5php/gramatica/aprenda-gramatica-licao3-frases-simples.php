    <h3>📌 1) Frases Afirmativas com です</h3>
    <p>です é usado no final da frase para dar cortesia e afirmar algo.</p>
    <p><strong>Estrutura:</strong><br>[Sujeito / Tema] は [Complemento] です。</p>
    <p><strong>Exemplo:</strong><br>わたし は がくせい です。<br>(Eu sou estudante.)</p>

    <h3>📌 2) Frases Negativas com ではありません</h3>
    <p>Para negar uma frase com です, usamos ではありません no final.</p>
    <p><strong>Estrutura:</strong><br>[Sujeito / Tema] は [Complemento] ではありません。</p>
    <p><strong>Exemplo:</strong><br>わたし は せんせい ではありません。<br>(Eu não sou professor.)</p>

