    <ul>
      <li>Uso da partícula から para indicar causa, motivo ou ponto inicial no tempo/espaço</li>
      <li>Uso da partícula まで para indicar limite ou ponto final no tempo/espaço</li>
      <li>Construção de frases simples com essas partículas</li>
