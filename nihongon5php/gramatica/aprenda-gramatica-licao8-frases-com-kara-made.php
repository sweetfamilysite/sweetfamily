    <h3>📌 1) Partícula から — Porque, desde</h3>
    <p>Indica a causa ou origem no tempo e espaço.</p>
    <p><strong>Exemplo de causa:</strong><br>つかれました。 から、やすみます。<br>(Estou cansado. Por isso vou descansar.)</p>
    <p><strong>Exemplo de ponto inicial:</strong><br>９じ から はたらきます。<br>(Trabalho a partir das 9 horas.)</p>

    <h3>📌 2) Partícula まで — Até</h3>
    <p>Indica o limite ou ponto final no tempo ou espaço.</p>
    <p><strong>Exemplo de ponto final:</strong><br>５じ まで はたらきます。<br>(Trabalho até as 5 horas.)</p>
    <p><strong>Exemplo de limite espacial:</strong><br>えき まで あるきます。<br>(Ando até a estação.)</p>

    <h3>📌 3) Exemplos de Frases</h3>
