    <p>📚 <strong>Lição 7 — Sons Modificados: Dakuten (゛) e Handakuten (゜)</strong></p>
    <p>✅ <strong>O que você vai aprender nesta lição</strong><br>
    Na Lição 7, você vai aprender como usar os símbolos de modificação de som no Hiragana:</p>
    <p><strong>Dakuten ( ゛)</strong> — chamado de tenten, são dois tracinhos que tornam o som sonoro (ex.: ka → ga).</p>
    <p><strong>Handakuten ( ゜)</strong> — chamado de maru, uma bolinha que transforma H em P (ex.: ha → pa).</p>
    <p>Saber usar estes sinais é essencial para escrever e entender palavras comuns em japonês.</p>

    <h3>📌 1) Linhas que recebem Dakuten</h3>
    <p>Dakuten (゛) transforma sons surdos em sonoros:</p>
    <p>KA → GA<br>SA → ZA<br>TA → DA<br>HA → BA</p>

    <table>
      <tr><th>Linha</th><th>A</th><th>I</th><th>U</th><th>E</th><th>O</th></tr>
      <tr><td>GA</td><td>が (ga)</td><td>ぎ (gi)</td><td>ぐ (gu)</td><td>げ (ge)</td><td>ご (go)</td></tr>
      <tr><td>ZA</td><td>ざ (za)</td><td>じ (ji)</td><td>ず (zu)</td><td>ぜ (ze)</td><td>ぞ (zo)</td></tr>
      <tr><td>DA</td><td>だ (da)</td><td>ぢ (ji)</td><td>づ (zu)</td><td>で (de)</td><td>ど (do)</td></tr>
      <tr><td>BA</td><td>ば (ba)</td><td>び (bi)</td><td>ぶ (bu)</td><td>べ (be)</td><td>ぼ (bo)</td></tr>
    </table>

    <p>📌 Obs.: じ (ji) também vem de し (shi).<br>
    ぢ (ji) e づ (zu) são usados em poucas palavras específicas.</p>

    <h3>📌 2) Linha que recebe Handakuten</h3>
    <p>Handakuten (゜) só aparece na Linha HA, criando a linha PA:</p>

    <table>
      <tr><th>Linha</th><th>A</th><th>I</th><th>U</th><th>E</th><th>O</th></tr>
      <tr><td>PA</td><td>ぱ (pa)</td><td>ぴ (pi)</td><td>ぷ (pu)</td><td>ぺ (pe)</td><td>ぽ (po)</td></tr>
    </table>

    <h3>📌 3) Palavras de Exemplo</h3>
    <table>
      <tr><th>Palavra</th><th>Hiragana</th><th>Significado</th></tr>
