    </table>

    <h3>📌 4) Frases Curtas</h3>
    <p>がくせい です。<br>Significado: É um estudante.</p>
    <p>ざっし を よみます。<br>Significado: (Eu) leio uma revista.</p>
    <p>でんわ です。<br>Significado: É um telefone.</p>
    <p>ぱん を たべます。<br>Significado: (Eu) como pão.</p>

    <h3>📌 5) Resumo</h3>
    <p>✔️ O Dakuten (゛) adiciona voz: KA → GA, SA → ZA, TA → DA, HA → BA.<br>
    ✔️ O Handakuten (゜) transforma HA em PA.<br>
    ✔️ O símbolo faz toda a diferença — sem ele, o som muda completamente.<br>
    ✔️ Escreva e leia com atenção para não confundir sons modificados.</p>

