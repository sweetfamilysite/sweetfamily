    <p>📚 <strong>Lição 6 — Combinações Yōon (きゃ きゅ きょ)</strong></p>
    <p>✅ <strong>O que você vai aprender nesta lição</strong><br>
    Na Lição 6, você vai aprender as combinações especiais do Hiragana, chamadas Yōon.<br>
    Essas combinações juntam uma sílaba da coluna I com um pequeno や (ya), ゆ (yu) ou よ (yo). Isso cria sons como kya, shu, cho, muito usados em palavras do dia a dia.</p>

    <h3>📌 1) Como funciona o Yōon</h3>
    <p>Para formar o Yōon, pegue uma sílaba da linha I e junte com ゃ (ya), ゅ (yu) ou ょ (yo) (sempre pequenos).<br>
    Não se usa a forma grande や, ゆ, よ — sempre pequena.</p>
    <p>Exemplos de base: き (ki), し (shi), ち (chi), に (ni), ひ (hi), み (mi), り (ri).</p>

    <h3>📌 2) Principais Combinações</h3>
