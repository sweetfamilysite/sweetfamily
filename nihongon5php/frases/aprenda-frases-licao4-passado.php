    <h3>📌 1) Formação do Passado Afirmativo</h3>
    <p>Substitua ます por ました para formar o passado afirmativo:</p>
    <ul>
      <li>たべます → たべました (comi)</li>
      <li>のみます → のみました (bebi)</li>
      <li>いきます → いきました (fui)</li>
    </ul>

    <h3>📌 2) Formação do Passado Negativo</h3>
    <p>Substitua ます por ませんでした para formar o passado negativo:</p>
    <ul>
      <li>たべます → たべませんでした (não comi)</li>
      <li>のみます → のみませんでした (não bebi)</li>
      <li>いきます → いきませんでした (não fui)</li>
    </ul>

