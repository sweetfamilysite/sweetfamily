    <h3>📌 1) Verbos no Presente Negativo — Forma ません</h3>
    <p>Para transformar um verbo em ます no negativo, substituímos ます por ません:</p>
    <ul>
      <li>たべます → たべません (não como)</li>
      <li>のみます → のみません (não bebo)</li>
      <li>いきます → いきません (não vou)</li>
    </ul>

    <h3>📌 2) Uso das Partículas から e まで</h3>
    <table>
      <thead style="background-color: #ffe66d;">
        <tr>
          <th>Partícula</th>
          <th>Uso</th>
          <th>Exemplo</th>
          <th>Tradução</th>
        </tr>
      </thead>
      <tbody>
        <tr><td>から</td><td>Indica ponto inicial no tempo ou lugar</td><td>９じ から はたらきます。</td><td>Trabalho a partir das 9 horas.</td></tr>
        <tr><td>まで</td><td>Indica ponto final no tempo ou lugar</td><td>５じ まで はたらきます。</td><td>Trabalho até as 5 horas.</td></tr>
      </tbody>
    </table>

