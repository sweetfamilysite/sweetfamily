        <tr><td>あげます</td><td>Dar para alguém</td><td>ともだち に プレゼント を あげます。</td><td>Dou um presente para um amigo.</td></tr>
        <tr><td>もらいます</td><td>Receber de alguém</td><td>ともだち に プレゼント を もらいました。</td><td>Recebi um presente de um amigo.</td></tr>
      </tbody>
    </table>

    <h3>📌 3) Expressar Habilidades: できます / じょうず</h3>
    <p><strong>できます:</strong> verbo para “poder fazer” algo, geralmente para habilidades ou permissões.<br>
    <em>Exemplo:</em> にほんご が できます。 (Eu posso falar japonês.)</p>
    <p><strong>じょうず:</strong> adjetivo para “ser bom em” algo.<br>
    <em>Exemplo:</em> ピアノ が じょうず です。 (É bom no piano.)</p>

