    <h3>📌 1) Fazer Pedidos com ください</h3>
    <p>Para pedir algo educadamente, usamos o verbo no て-forma + ください:</p>
    <p><em>Exemplos:</em><br>
    みず を ください。 (Por favor, me dê água.)<br>
    まって ください。 (Por favor, espere.)</p>

    <h3>📌 2) Dar e Receber: あげます / もらいます</h3>
    <table>
      <thead style="background-color: #ffe66d;">
        <tr>
          <th>Verbo</th>
          <th>Uso</th>
          <th>Exemplo</th>
