    <h3>📌 1) Estrutura Básica da Frase</h3>
    <p><strong>Frase afirmativa:</strong><br>
    [Sujeito / Tema] は [Complemento] です。</p>
    <p><em>Exemplo:</em><br>
    わたし は がくせい です。<br>
    (Eu sou estudante.)</p>

    <p><strong>Frase negativa:</strong><br>
    [Sujeito / Tema] は [Complemento] では ありません。</p>
    <p><em>Exemplo:</em><br>
    あなた は せんせい では ありません。<br>
    (Você não é professor.)</p>

    <p><strong>Pergunta:</strong><br>
    [Sujeito / Tema] は [Complemento] です か。</p>
    <p><em>Exemplo:</em><br>
    かれ は にほんじん です か。<br>
    (Ele é japonês?)</p>

