      <li>Como expressar gostos e desgostos com すき (gostar) e きらい (não gostar)</li>
      <li>Como usar os verbos あります e います para indicar existência de coisas e pessoas</li>
      <li>Construção de frases simples para expressar sentimentos e existência</li>
