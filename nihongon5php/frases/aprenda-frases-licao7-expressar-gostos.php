    <h3>📌 1) Expressar Gostos e Preferências</h3>
    <p>Para dizer que gosta de algo, usamos:<br>
    <strong>[Objeto] が すき です。</strong></p>
    <p><em>Exemplo:</em><br>
    すし が すき です。 (Eu gosto de sushi.)</p>

    <p>Para dizer que não gosta, usamos:<br>
    <strong>[Objeto] が きらい です。</strong></p>
    <p><em>Exemplo:</em><br>
    トマト が きらい です。 (Eu não gosto de tomate.)</p>

    <h3>📌 2) Verbo あります — Existência de coisas inanimadas</h3>
    <p>Usado para indicar que algo existe (objetos, plantas, lugares).</p>
    <p><em>Exemplo (frase errada para destaque):</em><br>
    いぬ が ありません。 (Não tem cachorro.)</p>
    <p>Frase correta:<br>
    いえ に きんぎょ が います。 (Tem um peixe dourado em casa.)</p>

    <h3>📌 3) Verbo います — Existência de seres animados</h3>
    <p>Usado para indicar a existência de pessoas e animais.</p>
    <p><em>Exemplo:</em><br>
    ともだち が います。 (Tenho amigo(s).)</p>

