    <h2>✅ O que você vai aprender nesta lição</h2>
    <ul>
      <li>Uso da partícula も para inclusão ("também")</li>
      <li>Uso da partícula と para enumeração e companhia ("e", "com")</li>
      <li>Uso da partícula の para posse e descrição ("de")</li>
      <li>Construção de frases simples com essas partículas</li>
      <li>Exemplos práticos e exercícios para fixação</li>
    </ul>

    <h3>📌 1) Partícula も (também)</h3>
    <p>Substitui a partícula は para indicar inclusão, algo que também é válido.</p>
    <p><em>Exemplo:</em><br>
    わたし は がくせい です。<br>
    あなた も がくせい です。<br>
    (Eu sou estudante. Você também é estudante.)</p>

    <h3>📌 2) Partícula と (e, com)</h3>
    <p>Usada para enumerar itens ou indicar companhia.</p>
    <p><strong>Exemplo (enumeração):</strong><br>
    りんご と みかん を たべます。<br>
    (Como maçã e tangerina.)</p>
    <p><strong>Exemplo (companhia):</strong><br>
    ともだち と いきます。<br>
    (Vou com amigo.)</p>

    <h3>📌 3) Partícula の (de / posse)</h3>
    <p>Indica posse, relação ou descrição entre dois substantivos.</p>
    <p><strong>Exemplo:</strong><br>
    わたし の くるま。<br>
    (Meu carro.)</p>
    <p>Também usada para descrever características:<br>
    にほん の ほん。<br>
    (Livro do Japão / livro japonês.)</p>

