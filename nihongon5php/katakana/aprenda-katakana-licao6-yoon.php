    Essas combinações são essenciais para palavras importadas, nomes e marcas, aparecendo o tempo todo.</p>

    <h3>📌 1) O que é o Yōon no Katakana</h3>
    <p>O Yōon junta uma sílaba da coluna I com um pequeno ャ (ya), ュ (yu) ou ョ (yo).</p>
    <p>O som resultante é compacto: ki + ya = kya (キャ).</p>
    <p><strong>Atenção:</strong> O ャュョ sempre é pequeno no final — se for grande, o som não combina!</p>

