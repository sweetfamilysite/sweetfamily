    <p>📚 <strong>Katakana — Lição 1: Introdução</strong></p>
    <p>✅ <strong>O que você vai aprender nesta lição</strong><br>
    Nesta primeira lição de Katakana, você vai entender o que é o Katakana, quando é usado e por que ele é essencial, mesmo para quem está focando no JLPT N5.</p>

    <h3>📌 1) O que é o Katakana?</h3>
    <p>O Katakana (カタカナ) é um dos três sistemas de escrita do japonês.</p>
    <p>Assim como o Hiragana, o Katakana é silábico: cada caractere representa uma sílaba, não uma letra isolada.</p>
    <p>O Katakana tem os mesmos sons do Hiragana, mas o formato dos caracteres é mais reto e angular.</p>
    <p>Cada som do Hiragana tem um equivalente em Katakana. Por exemplo: あ (a) → ア (a).</p>

    <h3>📌 2) Para que serve o Katakana?</h3>
    <p>O Katakana é usado principalmente para:</p>
    <ul>
      <li>Escrever palavras estrangeiras adaptadas ao japonês (ex.: コンピュータ = computador).</li>
      <li>Escrever onomatopeias (sons, ruídos) — muito comuns em mangás.</li>
      <li>Dar ênfase, como se fosse negrito ou itálico.</li>
      <li>Escrever nomes estrangeiros.</li>
      <li>Nome científico de plantas, animais, ou palavras técnicas.</li>
      <li>Algumas marcas, sinais e placas.</li>
    </ul>

    <h3>📌 3) Por que aprender Katakana no JLPT N5?</h3>
    <p>O JLPT N5 cobra vocabulário básico, e várias palavras de uso comum aparecem em Katakana — principalmente nomes de comidas, objetos, lugares ou marcas.</p>
    <p>Mesmo para ler cartazes, cardápios e manuais simples, o Katakana é indispensável.</p>
    <p>Saber Hiragana não substitui o Katakana — é preciso conhecer os dois para entender textos básicos.</p>

    <h3>📌 4) O que vem a seguir?</h3>
    <p>Na próxima lição, vamos começar a aprender o Katakana básico, linha por linha, no mesmo padrão que usamos no Hiragana:</p>
    <ul>
      <li>Sons puros (A, KA, SA, etc.)</li>
      <li>Sons modificados (Dakuten, Handakuten)</li>
      <li>Combinações especiais (pequeno ャ, ュ, ョ)</li>
    </ul>

    <h3>✅ Resumo</h3>
