    <p>✅ <strong>O que você vai aprender nesta lição</strong><br>
    Na Lição 7, você vai entender como usar os símbolos que modificam o som das sílabas no Katakana:</p>
    <p><strong>Dakuten (゛)</strong> — os dois tracinhos que tornam um som sonoro (ex.: カ → ガ).</p>
    <p><strong>Handakuten (゜)</strong> — a bolinha que transforma o som H em P (ex.: ハ → パ).</p>
    <p>Estes símbolos aparecem o tempo todo em palavras estrangeiras.</p>

    <h3>📌 1) Como funciona o Dakuten (゛)</h3>
    <p>O Dakuten adiciona voz às sílabas:</p>
    <ul>
      <li>Linha KA vira GA</li>
      <li>Linha SA vira ZA</li>
      <li>Linha TA vira DA</li>
      <li>Linha HA vira BA</li>
    </ul>

